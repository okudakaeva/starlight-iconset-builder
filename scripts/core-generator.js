const fs = require('fs');
const path = require('path');
const { optimize } = require('svgo');
const { parseSync, stringify } = require('svgson');

const MULTICOLOR_FOLDERS = new Set(['brands', 'multicolor', 'color']);
const SHAPE_TAGS = new Set(['path', 'circle', 'rect', 'ellipse', 'polygon', 'polyline', 'line']);

function extractDimensions (svgNode) {
    const { width, height, viewBox } = svgNode.attributes;

    if (width && height) {
        const parsedW = parseFloat(width);
        const parsedH = parseFloat(height);
        if (!Number.isNaN(parsedW) && !Number.isNaN(parsedH)) {
            return { width: `${ parsedW }px`, height: `${ parsedH }px` };
        }
    }

    if (viewBox) {
        const parts = viewBox.trim().split(/[\s,]+/);
        if (parts.length === 4) {
            const parsedW = parseFloat(parts[2]);
            const parsedH = parseFloat(parts[3]);
            if (!Number.isNaN(parsedW) && !Number.isNaN(parsedH)) {
                return { width: `${ parsedW }px`, height: `${ parsedH }px` };
            }
        }
    }

    return { width: '24px', height: '24px' };
}

/**
 * @param {import('svgson').INode} node
 * @param {boolean} [inheritNoFill=false]
 */
function applyDynamicFill (node, inheritNoFill = false) {
    const isNoFill = inheritNoFill || node.attributes.fill?.toLowerCase() === 'none';

    if (SHAPE_TAGS.has(node.name)) {
        const currentFill = node.attributes.fill;
        if (!isNoFill && (!currentFill || currentFill.toLowerCase() !== 'none')) {
            node.attributes.fill = '#{$fill}';
        }

        const currentStroke = node.attributes.stroke;
        if (currentStroke && currentStroke.toLowerCase() !== 'none') {
            node.attributes.stroke = '#{$fill}';
        }
    }

    if (Array.isArray(node.children)) {
        node.children.forEach((child) => applyDynamicFill(child, isNoFill));
    }
}

function processSvgFile (filePath, isMulticolorSet) {
    const rawSvg = fs.readFileSync(filePath, 'utf8');
    const fileName = path.basename(filePath);
    const isColorFile = isMulticolorSet || fileName.endsWith('.color.svg');
    const iconName = fileName.replace(/\.color\.svg$/i, '').replace(/\.svg$/i, '');

    const optimized = optimize(rawSvg, {
        path: filePath,
        multipass: true,
        plugins: [
            {
                name: 'preset-default',
                params: {
                    overrides: {
                        removeViewBox: false,
                    },
                },
            },
        ],
    });

    const ast = parseSync(optimized.data);
    const { width, height } = extractDimensions(ast);

    if (!isColorFile) {
        if (ast.attributes.stroke && ast.attributes.stroke.toLowerCase() !== 'none') {
            ast.attributes.stroke = '#{$fill}';
        }
        applyDynamicFill(ast);
    }

    delete ast.attributes.width;
    delete ast.attributes.height;

    const cleanSvgString = stringify(ast);

    return {
        name: iconName,
        width,
        height,
        isMulticolor: isColorFile,
        svg: cleanSvgString,
    };
}

function generateIconSet (sourceDir, outputDir, setName) {
    if (!fs.existsSync(outputDir)) {
        fs.mkdirSync(outputDir, { recursive: true });
    }

    const files = fs
            .readdirSync(sourceDir)
            .filter((file) => file.toLowerCase().endsWith('.svg'))
            .sort();

    const isMulticolorSet = MULTICOLOR_FOLDERS.has(setName.toLowerCase());
    const icons = files.map((file) => processSvgFile(path.join(sourceDir, file), isMulticolorSet));

    let sassContent = `// Auto-generated by starlight-iconset-builder. Do not edit manually.\n`;
    sassContent += `@use "sass:meta"\n\n`;

    icons.forEach((icon) => {
        const fnName = `sib-${ setName }-${ icon.name }-icon`;
        sassContent += `@function ${ fnName }($fill: #232634)\n`;
        sassContent += `  @return '${ icon.svg }'\n\n`;
    });

    sassContent += `$sib-${ setName }-icons: (\n`;
    icons.forEach((icon) => {
        const fnName = `sib-${ setName }-${ icon.name }-icon`;
        sassContent += `  '${ icon.name }': (\n`;
        sassContent += `    fn: meta.get-function('${ fnName }'),\n`;
        sassContent += `    width: ${ icon.width },\n`;
        sassContent += `    height: ${ icon.height },\n`;
        sassContent += `    multicolor: ${ icon.isMulticolor }\n`;
        sassContent += `  ),\n`;
    });
    sassContent += `)\n`;

    const outputFilePath = path.join(outputDir, `_${ setName }-icons.sass`);
    fs.writeFileSync(outputFilePath, sassContent, 'utf8');

    return {
        setName,
        icons,
    };
}

function generateAllSets (parentSourceDir, outputDir) {
    if (!fs.existsSync(outputDir)) {
        fs.mkdirSync(outputDir, { recursive: true });
    }

    const entries = fs.readdirSync(parentSourceDir, { withFileTypes: true });
    const setDirs = entries
            .filter((entry) => entry.isDirectory())
            .map((entry) => entry.name)
            .sort();

    const generatedSets = setDirs.map((setName) =>
            generateIconSet(path.join(parentSourceDir, setName), outputDir, setName)
    );

    let indexContent = `// Auto-generated registry of all icon sets.\n`;
    generatedSets.forEach(({ setName }) => {
        indexContent += `@use "${ setName }-icons" as *\n`;
    });

    indexContent += `\n$sib-icons-list: (\n`;
    generatedSets.forEach(({ setName }) => {
        indexContent += `  '${ setName }': $sib-${ setName }-icons,\n`;
    });
    indexContent += `)\n`;

    fs.writeFileSync(path.join(outputDir, '_icons.sass'), indexContent, 'utf8');

    return generatedSets;
}

module.exports = {
    generateIconSet,
    generateAllSets,
};
